"""cure_oracle/sonnet_score.py — Sonnet-Score engine.

Maps the quantum candy/spiral state onto a structured musical score (JSON).
Designed for the Hermione's-Wand drive-board game:

  Dragon ride (螺旋) → tempo / tilt-rate
  Candy grab (キャンディ群) → musical motif per slot
  Wand attack on grid (ドライブ板) → score events
  MENTE ascent rate → musical intensity / octave shift

Musical layer mapping (harp-inspired 箏三音域)
──────────────────────────────────────────────
  S4 広目天 (q ≥ 0.75)   → 大甲音 (highest octave) — Dragon ascent motif
  S1 多聞天 (0.50–0.75)  → 甲音  (middle octave)   — Wand sweep
  S3 持国天 (0.25–0.50)  → 呂音  (lower octave)    — Grid pulse
  S2 増長天 (q < 0.25)   → 呂音 bass               — Candy grab anchor

Candy shape → musical character
  CUBE  → block chord   (四角い和音)   — Baroque complexity
  RING  → arpeggio      (環状アルペジオ) — Classical flow
  TREE  → tremolo       (分岐トレモロ)  — Beethoven bridge
  LINE  → scale run     (直線スケール)  — Romantic ascent
  STAR  → staccato burst (放射スタッカート) — Inner world explosion

Spiral events → score embellishments
  entanglement_shot  → chord split (同音2重奏)
  superposition_dash → grace notes (装飾音)
  luna_event         → key change  (転調)

Offline mode is the primary path (no external API needed).
When Gemini is available, commentary is enriched via GeminiCandyFlash.
"""

from __future__ import annotations

import datetime
import hashlib
import math
import uuid
from dataclasses import dataclass, field
from typing import Optional

from cure_oracle.birth import make_sig_receipt
from cure_oracle.mente import MENTE_CONST

# ── constants ─────────────────────────────────────────────────────────────────

DRIVE_BOARD_1_COLS = 4
DRIVE_BOARD_1_ROWS = 4
DRIVE_BOARD_2_COLS = 8
DRIVE_BOARD_2_ROWS = 4

# Harp register names (箏音域)
REGISTER_S4 = "大甲音"   # highest
REGISTER_S1 = "甲音"
REGISTER_S3 = "呂音"
REGISTER_S2 = "呂音-bass"

SLOT_TO_REGISTER = {
    "S4": REGISTER_S4,
    "S1": REGISTER_S1,
    "S3": REGISTER_S3,
    "S2": REGISTER_S2,
}

# Shape → musical character
SHAPE_MOTIF = {
    "CUBE": {"name": "block_chord",    "jp": "四角い和音",   "era": "baroque"},
    "RING": {"name": "arpeggio",       "jp": "環状アルペジオ", "era": "classical"},
    "TREE": {"name": "tremolo",        "jp": "分岐トレモロ",  "era": "beethoven"},
    "LINE": {"name": "scale_run",      "jp": "直線スケール",  "era": "romantic"},
    "STAR": {"name": "staccato_burst", "jp": "放射スタッカート","era": "inner_world"},
}

# BPM range mapped from teleport angle (0–360°) → 80–160 BPM
_BPM_MIN, _BPM_MAX = 80, 160


# ── data classes ──────────────────────────────────────────────────────────────

@dataclass
class DriveCell:
    """One cell on a drive board that the wand attacked."""
    col:    int
    row:    int
    shape:  str            # candy shape that attacked this cell
    slot:   str            # S1–S4
    motif:  str            # musical motif name
    q:      float          # quality score
    effect: str            # "ascent" | "pulse" | "anchor" | "sweep"


@dataclass
class ScoreEvent:
    """A single musical event generated by a wand attack."""
    beat:       float      # beat position within the bar (1.0 = beat 1)
    duration:   float      # in beats
    register:   str        # 大甲音 / 甲音 / 呂音 / 呂音-bass
    motif:      str
    intensity:  float      # 0.0 – 1.0
    embellishment: Optional[str] = None  # chord_split / grace_notes / key_change


@dataclass
class DriveBoard:
    """Grid of wand-attack results (ドライブ板)."""
    name:    str            # "drive_board_1" | "drive_board_2"
    cols:    int
    rows:    int
    cells:   list[DriveCell] = field(default_factory=list)

    def to_grid(self) -> list[list[Optional[str]]]:
        """Return 2-D grid of shape names (None = empty)."""
        grid = [[None] * self.cols for _ in range(self.rows)]
        for c in self.cells:
            if 0 <= c.row < self.rows and 0 <= c.col < self.cols:
                grid[c.row][c.col] = c.shape
        return grid


@dataclass
class SonnetScoreResult:
    """Full output of one Sonnet-Score computation."""
    score_id:        str = field(default_factory=lambda: str(uuid.uuid4()))
    born_at:         str = field(
        default_factory=lambda: datetime.datetime.now(datetime.timezone.utc).isoformat()
    )
    bpm:             int = 120
    bars:            int = 4
    tilt_rate:       float = 0.0        # ascent tilt (spiral angle → %)
    ascent_rate:     float = 0.0        # MENTE ascent 0–100 %
    mente_total:     float = 0.0
    mente_achieved:  bool = False
    key:             str = "D"          # musical key
    mode_name:       str = "dorian"     # dorian / major / pentatonic / chromatic
    era:             str = "classical"  # baroque / classical / beethoven / romantic / inner_world
    events:          list[ScoreEvent] = field(default_factory=list)
    board_1:         DriveBoard = field(
        default_factory=lambda: DriveBoard("drive_board_1", DRIVE_BOARD_1_COLS, DRIVE_BOARD_1_ROWS)
    )
    board_2:         DriveBoard = field(
        default_factory=lambda: DriveBoard("drive_board_2", DRIVE_BOARD_2_COLS, DRIVE_BOARD_2_ROWS)
    )
    embellishments:  list[str] = field(default_factory=list)   # active spiral events
    commentary:      str = ""
    observe_receipt: dict = field(default_factory=dict)


# ── helpers ───────────────────────────────────────────────────────────────────

def _angle_to_bpm(angle: float) -> int:
    """Map teleport angle 0–360° to BPM 80–160."""
    ratio = angle / 360.0
    return round(_BPM_MIN + ratio * (_BPM_MAX - _BPM_MIN))


def _mente_to_ascent(mente_total: float) -> float:
    """Normalize MENTE total to 0–100% ascent rate."""
    return min(100.0, round(mente_total / MENTE_CONST * 100.0, 2))


def _mente_to_key(mente_total: float) -> tuple[str, str]:
    """Map MENTE total → musical key + mode (古典→ロマン派 progression)."""
    if mente_total >= MENTE_CONST:          # 四天王全顕現 → chromatic inner world
        return "C#", "chromatic"
    if mente_total >= MENTE_CONST * 0.75:   # Beethoven bridge
        return "C", "major"
    if mente_total >= MENTE_CONST * 0.50:   # Classical
        return "D", "dorian"
    if mente_total >= MENTE_CONST * 0.25:   # Baroque
        return "G", "pentatonic"
    return "E", "minor"                     # Early / anchor


def _mente_to_era(mente_total: float) -> str:
    if mente_total >= MENTE_CONST:            return "inner_world"
    if mente_total >= MENTE_CONST * 0.75:     return "romantic"
    if mente_total >= MENTE_CONST * 0.50:     return "beethoven"
    if mente_total >= MENTE_CONST * 0.25:     return "classical"
    return "baroque"


def _shape_effect(slot: str) -> str:
    return {"S4": "ascent", "S1": "sweep", "S3": "pulse", "S2": "anchor"}.get(slot, "pulse")


def _place_wand_attacks(
    slot_runs: dict[str, object],   # slot → AcceleratorRun
    board_1: DriveBoard,
    board_2: DriveBoard,
) -> list[ScoreEvent]:
    """
    Map synthesized slot→run onto drive boards using a spiral Fibonacci placement.
    Returns the list of ScoreEvents.
    """
    events: list[ScoreEvent] = []
    slot_order = ["S4", "S1", "S3", "S2"]
    # Fibonacci spiral positions on board_1 (4×4)
    fib_positions_b1 = [(0, 0), (1, 0), (1, 1), (0, 1), (2, 0), (2, 1), (3, 0), (0, 2)]
    # Drive board 2 (8×4): fill left-to-right per slot row
    b2_row_map = {"S4": 0, "S1": 1, "S3": 2, "S2": 3}

    beat_cursor = 1.0
    fib_idx = 0
    for slot in slot_order:
        run = slot_runs.get(slot)
        if run is None:
            beat_cursor += 0.5
            continue

        motif = SHAPE_MOTIF.get(run.shape, {}).get("name", "scale_run")
        register = SLOT_TO_REGISTER.get(slot, "呂音")
        effect = _shape_effect(slot)
        intensity = run.q

        # Board 1 cell
        if fib_idx < len(fib_positions_b1):
            col, row = fib_positions_b1[fib_idx]
            board_1.cells.append(DriveCell(
                col=col, row=row, shape=run.shape, slot=slot,
                motif=motif, q=run.q, effect=effect,
            ))
            fib_idx += 1

        # Board 2 cell (column = round(q * (cols-1)))
        b2_col = min(board_2.cols - 1, round(run.q * (board_2.cols - 1)))
        b2_row = b2_row_map.get(slot, 0)
        board_2.cells.append(DriveCell(
            col=b2_col, row=b2_row, shape=run.shape, slot=slot,
            motif=motif, q=run.q, effect=effect,
        ))

        # Score event
        duration = 2.0 if slot == "S4" else 1.0
        events.append(ScoreEvent(
            beat=beat_cursor,
            duration=duration,
            register=register,
            motif=motif,
            intensity=intensity,
        ))
        beat_cursor += duration

    return events


def _apply_spiral_embellishments(
    events: list[ScoreEvent],
    spiral: dict,
) -> list[str]:
    """Add embellishments to events based on spiral quantum events."""
    ev = spiral.get("events", {})
    applied: list[str] = []
    if ev.get("entanglement_shot") and events:
        events[0].embellishment = "chord_split"
        applied.append("chord_split")
    if ev.get("superposition_dash") and len(events) > 1:
        events[1].embellishment = "grace_notes"
        applied.append("grace_notes")
    if ev.get("luna_event") and events:
        events[-1].embellishment = "key_change"
        applied.append("key_change")
    return applied


# ── sig-receipt ───────────────────────────────────────────────────────────────

def _build_sonnet_receipt(result: SonnetScoreResult) -> dict:
    fingerprint = hashlib.sha256(
        f"{result.score_id}|{result.bpm}|{result.mente_total:.6f}|{result.era}".encode()
    ).hexdigest()
    sig_code = "CUBE-φ.618-ε.001" if result.mente_achieved else "LINE-√.414-ε.010"
    epsilon = 0.001 if result.mente_achieved else 0.010
    cert = {
        "certificate_id": result.score_id,
        "born_at":         result.born_at,
        "backend":         f"cure-os/sonnet-score/{result.era}",
        "qpu_seconds":     0,
        "bitstring":       fingerprint[:16],
    }
    return make_sig_receipt(cert, sig_code, epsilon, result.mente_total)


# ── SonnetScore ───────────────────────────────────────────────────────────────

class SonnetScore:
    """Hermione's-Wand musical score generator.

    Converts a candy-group accelerator result + spiral state into a
    structured Sonnet-Score (musical events, drive boards, ascent rate).
    Works fully offline; no external API key required.

    Parameters
    ----------
    bars : int
        Length of the generated score in bars (default 4).
    """

    def __init__(self, bars: int = 4) -> None:
        self._bars = bars

    def compute(
        self,
        accelerator_result,              # AcceleratorResult from VirtualAccelerator
        spiral: dict,                    # dict from round_circuit()
        commentary: str = "",
    ) -> SonnetScoreResult:
        """Generate a SonnetScoreResult from quantum state.

        Parameters
        ----------
        accelerator_result:
            Output of VirtualAccelerator.run().
        spiral:
            Output of round_circuit().
        commentary:
            Optional Gemini commentary to embed in the score.
        """
        syn = accelerator_result.synthesized
        angle_a = spiral.get("teleport_angle_a", 180.0)
        bpm = _angle_to_bpm(angle_a)
        tilt_pct = round(angle_a / 360.0 * 100.0, 2)
        ascent = _mente_to_ascent(syn.mente_total)
        key, mode = _mente_to_key(syn.mente_total)
        era = _mente_to_era(syn.mente_total)

        result = SonnetScoreResult(
            bpm=bpm,
            bars=self._bars,
            tilt_rate=tilt_pct,
            ascent_rate=ascent,
            mente_total=round(syn.mente_total, 6),
            mente_achieved=syn.mente_achieved,
            key=key,
            mode_name=mode,
            era=era,
            commentary=commentary,
        )

        # Place wand attacks on drive boards, generate events
        events = _place_wand_attacks(syn.slots, result.board_1, result.board_2)
        result.events = events

        # Apply spiral embellishments
        result.embellishments = _apply_spiral_embellishments(events, spiral)

        # Sig-receipt
        result.observe_receipt = _build_sonnet_receipt(result)
        return result

    def compute_offline(
        self,
        shapes: list[str],
        shots: Optional[int] = 512,
        mode: str = "local",
        round_num: int = 1,
    ) -> SonnetScoreResult:
        """Full offline pipeline: accelerator + spiral + compute().

        Parameters
        ----------
        shapes:
            Candy group shapes.
        shots / mode / round_num:
            Forwarded to VirtualAccelerator and round_circuit.
        """
        from cure_oracle.accelerator import VirtualAccelerator
        from cure_oracle.round_circuit import round_circuit

        acc = VirtualAccelerator()
        acc_result = acc.run(shapes=shapes, shots=shots, mode=mode)
        spiral = round_circuit(round_num=round_num)
        commentary = (
            f"ドライブ板攻撃: 四天王スロット {list(acc_result.synthesized.slots.keys())} / "
            f"BPM={_angle_to_bpm(spiral.get('teleport_angle_a', 180.0))} / "
            f"ERA={_mente_to_era(acc_result.synthesized.mente_total)} / "
            f"MENTE={acc_result.synthesized.mente_total:.4f}"
        )
        return self.compute(acc_result, spiral, commentary)
